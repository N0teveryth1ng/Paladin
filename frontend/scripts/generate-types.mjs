#!/usr/bin/env node
/**
 * Generate the TypeScript view of the frozen generation schema.
 *
 * The architecture types are never written by hand. This script reads
 * schema/architecture.generation.schema.json as bytes, hashes it, and writes
 * two committed files:
 *
 *   src/types/architecture.generated.ts
 *   src/types/schema.ts
 *
 * It is deterministic: the same schema bytes always produce the same output.
 *
 * Usage:
 *   node scripts/generate-types.mjs                 # write the committed files
 *   node scripts/generate-types.mjs --stdout        # print the generated types
 *   node scripts/generate-types.mjs --schema <path> --stdout
 */

import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(HERE, '..');
const REPO = resolve(FRONTEND, '..');
const DEFAULT_SCHEMA = resolve(REPO, 'schema/architecture.generation.schema.json');
const GENERATED = resolve(FRONTEND, 'src/types/architecture.generated.ts');
const SCHEMA_TS = resolve(FRONTEND, 'src/types/schema.ts');

export function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex').toUpperCase();
}

export async function generate(schemaPath = DEFAULT_SCHEMA) {
  const bytes = await readFile(schemaPath);
  const hash = sha256(bytes);
  const schema = JSON.parse(bytes.toString('utf8'));

  const banner = [
    '/* eslint-disable */',
    '/* Generated by scripts/generate-types.mjs. Do not edit. */',
    '/* source: schema/architecture.generation.schema.json */',
    `/* sha256: ${hash} */`,
    '',
  ].join('\n');

  const generated = await compile(schema, 'ArchitectureDraft', {
    bannerComment: banner,
    additionalProperties: false,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    format: true,
    ignoreMinAndMaxItems: true,
    maxItems: -1,
    strictIndexSignatures: false,
    unknownAny: true,
    unreachableDefinitions: true,
    cwd: dirname(schemaPath),
    style: {
      printWidth: 100,
      tabWidth: 2,
      singleQuote: true,
      semi: true,
      trailingComma: 'none',
    },
  });

  const schemaTs = [
    '/* eslint-disable */',
    '/* Generated by scripts/generate-types.mjs. Do not edit. */',
    `export const SCHEMA_SHA256 = '${hash}';`,
    '',
  ].join('\n');

  return { hash, generated: normalize(generated), schemaTs: normalize(schemaTs) };
}

function normalize(text) {
  return `${text.replace(/\r\n/g, '\n').replace(/\n+$/, '')}\n`;
}

function arg(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

async function main() {
  const schemaPath = arg('--schema') ? resolve(arg('--schema')) : DEFAULT_SCHEMA;
  const { generated, schemaTs, hash } = await generate(schemaPath);

  if (process.argv.includes('--stdout')) {
    process.stdout.write(generated);
    return;
  }

  await mkdir(dirname(GENERATED), { recursive: true });
  await writeFile(GENERATED, generated, 'utf8');
  await writeFile(SCHEMA_TS, schemaTs, 'utf8');
  process.stdout.write(`generated types for schema ${hash}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
    process.exitCode = 1;
  });
}
