import { createHash } from 'node:crypto';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { generate } from '../../scripts/generate-types.mjs';
import { SCHEMA_SHA256 } from '../types/schema';

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(HERE, '../..');
const REPO = resolve(FRONTEND, '..');
const SCHEMA_PATH = resolve(REPO, 'schema/architecture.generation.schema.json');
const GENERATED_PATH = resolve(FRONTEND, 'src/types/architecture.generated.ts');
const SCHEMA_TS_PATH = resolve(FRONTEND, 'src/types/schema.ts');

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex').toUpperCase();
}

async function walk(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(path)));
    } else {
      files.push(path);
    }
  }
  return files;
}

describe('generated architecture types', () => {
  it('hashes the frozen schema exactly', async () => {
    const bytes = await readFile(SCHEMA_PATH);
    expect(sha256(bytes)).toBe(SCHEMA_SHA256);
  });

  it('matches a fresh generation byte for byte', async () => {
    const fresh = await generate(SCHEMA_PATH);
    const committed = await readFile(GENERATED_PATH, 'utf8');
    const committedSchema = await readFile(SCHEMA_TS_PATH, 'utf8');

    expect(fresh.hash).toBe(SCHEMA_SHA256);
    expect(fresh.generated).toBe(committed);
    expect(fresh.schemaTs).toBe(committedSchema);
  });

  it('carries the schema hash in the generated banner', async () => {
    const committed = await readFile(GENERATED_PATH, 'utf8');
    expect(committed).toContain(`/* sha256: ${SCHEMA_SHA256} */`);
    expect(committed).toContain('/* Generated by scripts/generate-types.mjs. Do not edit. */');
  });

  it('changes both the hash and the output for a schema copy with one extra property', async () => {
    const schema = JSON.parse(await readFile(SCHEMA_PATH, 'utf8')) as {
      properties: Record<string, unknown>;
    };
    schema.properties.extra_probe = { type: 'string' };

    const directory = await mkdtemp(join(tmpdir(), 'paladin-schema-'));
    const probePath = join(directory, 'probe.schema.json');
    await writeFile(probePath, `${JSON.stringify(schema, null, 2)}\n`, 'utf8');

    try {
      const fresh = await generate(SCHEMA_PATH);
      const probe = await generate(probePath);
      const committed = await readFile(GENERATED_PATH, 'utf8');

      expect(probe.hash).not.toBe(SCHEMA_SHA256);
      expect(probe.hash).not.toBe(fresh.hash);
      expect(probe.generated).not.toBe(committed);
      expect(probe.generated).toContain('extra_probe');
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });

  it('has no hand-written architecture interface outside the generated file', async () => {
    const files = (await walk(resolve(FRONTEND, 'src'))).filter(
      (file) =>
        /\.(ts|tsx)$/.test(file) &&
        !file.endsWith('architecture.generated.ts') &&
        !file.includes(`${join('src', 'test')}`) &&
        !file.includes(`${join('src', 'fixtures')}`),
    );

    const forbidden =
      /\b(?:interface|type)\s+(ArchitectureDraft|Architecture|Component|Connection|Group|Requirement|Assumption|Flag|RunMeta|Issue)\b/;

    const offenders: string[] = [];
    for (const file of files) {
      const text = await readFile(file, 'utf8');
      if (forbidden.test(text)) {
        offenders.push(file);
      }
    }

    expect(offenders).toEqual([]);
  });
});
